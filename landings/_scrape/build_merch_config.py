def slugify(url: str) -> str:
    tail = url.rstrip("/").rsplit("/", 1)[-1]
    return "".join(ch if ch.isalnum() else "-" for ch in tail).strip("-").lower()


def photo_src(item: dict) -> str:
    """Локальная веб-копия, иначе адрес на сайте заказчика.

    Расширения перебираются явно: оптимизатор пишет .jpg, но до его
    работы рядом лежит оригинал, у которого расширение как на сайте,
    включая .gif с заглавной буквы.
    """
    photos = item.get("photos") or []
    if not photos:
        return ""
    url = photos[0]
    stem = safe_name(url, slugify(item["url"]), 0).rsplit(".", 1)[0]
    for ext in ("jpg", "jpeg", "png", "webp", "gif"):
        local = WEB_DIR / f"{stem}.{ext}"
        if local.exists():
            return f"assets/web/{local.name}"
    return url


def clean_name(raw: str) -> str:
    """Приводит название к виду для карточки.

    Названия с сайта в разном регистре: «КРУЖКА БЕЛАЯ 330 МЛ» и
    «Кружка с логотипом». ВСЕ КАПСЫ на карточке выглядит как крик, а
    перед первым словом ставится большая буква. Внутренние слова не
    трогаются: «из нержавеющей стали» должно остаться строчным.
    """
    s = " ".join(str(raw or "").split()).strip(" ,.;:")
    if not s:
        return s
    if s.isupper():
        s = s.lower().capitalize()
    return s


def pick(items: list[dict], sub: str, limit: int) -> list[dict]:
    """Позиции подраздела без повторов по фотографии.

    Дедупликация по фото обязательна, и это не косметика. В «Магнитах
    виниловых» на сайте десять позиций, но это один товар с размерами
    5х5, 7х7, 10х15, 15х21 и так далее, и фотография у них одна и та же.
    Без проверки в блок попадали две карточки с одинаковым снимком под
    разными именами: человек видит два «разных» магнита и понимает,
    что это одно и то же, и перестаёт доверять остальному каталогу.

    Первая позиция группы фотографии запоминается, остальные с тем же
    снимком отбрасываются. Их различия перечисляются в specs выжившей
    позиции, поэтому варианты не теряются.
    """
    out = [i for i in items
           if i["section"] == "suvenirnaya-produktsiya"
           and i["subsection"] == sub
           and i.get("name")
           and i.get("photos")]
    # Раздел сайта не товар. У «Печати на ручках» есть собственная
    # страница-раздел с такой же фотографией, как у первого товара
    # внутри неё, и она попадала в каталог как отдельная позиция.
    # Название раздела известно: оно равно заголовку подраздела на сайте.
    out = [i for i in out if " ".join(str(i["name"]).split()).lower() != sub.replace("-", " ")]
    out.sort(key=lambda x: (0 if x.get("priceTiers") else 1, x["name"]))

    seen_img: set[str] = set()
    picked: list[dict] = []
    for i in out:
        key = i["photos"][0]
        if key in seen_img:
            continue
        seen_img.add(key)
        picked.append(i)
        if len(picked) >= limit:
            break
    return picked


def variants_of(items: list[dict], sub: str, photo: str) -> list[str]:
    """Названия остальных позиций с той же фотографией.

    Это варианты одного товара: у магнитов разные размеры, у одежды
    иногда цвета. Их имеет смысл назвать в карточке, иначе человек не
    поймёт, что входит в заказ.
    """
    names = []
    for i in items:
        if i["section"] != "suvenirnaya-produktsiya" or i["subsection"] != sub:
            continue
        if not i.get("photos") or i["photos"][0] != photo:
            continue
        names.append(" ".join(str(i["name"]).split()))
    return names


