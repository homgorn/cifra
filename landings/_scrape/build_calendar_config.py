def pick(items: list[dict], parts: tuple[str, ...]) -> list[dict]:
    out = [i for i in items if any(p in i["url"] for p in parts)]
    return sorted(out, key=lambda x: x["name"])


def slugify(url: str) -> str:
    tail = url.rstrip("/").rsplit("/", 1)[-1]
    return "".join(ch if ch.isalnum() else "-" for ch in tail).strip("-").lower()


def photo_src(item: dict) -> str:
    """Путь к фотографии позиции: локальная веб-версия, иначе адрес на сайте.

    Локальная версия важна по весу: оригиналы с сайта весят до 9 МБ, после
    оптимизации те же снимки весят 60-200 КБ, а превью в карточке
    показывается шириной 1100 пикселей. Адрес на сайте остаётся запасным
    вариантом на случай, если локальный файл ещё не оптимизирован.
    """
    photos = item.get("photos") or []
    if not photos:
        return ""
    url = photos[0]
    stem = safe_name(url, slugify(item["url"]), 0).rsplit(".", 1)[0]
    # Оптимизатор всегда пишет .jpg, но если локальный файл ещё не
    # оптимизирован, рядом лежит оригинал, и у него расширение как на
    # сайте, включая .gif с заглавной буквы. Каталог на Windows регистр
    # не различает, поэтому список расширений перебирается явно.
    for ext in ("jpg", "jpeg", "png", "webp", "gif"):
        local = WEB_DIR / f"{stem}.{ext}"
        if local.exists():
            return f"assets/web/{local.name}"
    return url


def specs_from_name(name: str, tiers: list[dict]) -> str:
    """Спецификация позиции. Только то, что следует из названия и тиражей.

    Настоящего описания у позиции нет: на сайте оно одно на весь раздел.
    Поэтому в specs попадает разбор названия, а не пересказ чужого текста.
    """
    parts = [name]
    if tiers:
        qtys = [t["qty"] for t in tiers]
        parts.append(f"тиражи от {min(qtys)} до {max(qtys)} шт")
    return " · ".join(parts)


def build_group(items: list[dict]) -> list[dict]:
    """Карточки группы без повторов по фотографии.

    Вариант с тем же снимком не показывается второй карточкой: он уже
    назван в подписи выжившей позиции. Иначе на странице стоят два
    одинаковых снимка под двумя почти одинаковыми названиями, и человек
    не понимает, это два товара или один.
    """
    cards: list[dict] = []
    seen: set[str] = set()
    for i in items:
        photo = (i.get("photos") or [""])[0]
        card = build_item(i, items)
        if photo in seen:
            continue
        seen.add(photo)
        cards.append(card)
    return cards


def build_item(i: dict, siblings: list[dict] | None = None) -> dict:
    """Карточка позиции.

    `siblings` нужны ради вариантов. На сайте «Квартальный календарь
    PREMIUM, прозрачный пластик» с 1 рекламным полем и с 3 рекламными
    полями это два товара с одной фотографией. Без обработки на странице
    появлялись две карточки с одинаковым снимком, и человек видел два
    «разных» календаря, которые на самом деле отличаются числом полей.
    """

    tiers = i.get("priceTiers") or []
    item = {
        "id": slugify(i["url"]),
        # Адрес исходника едет вместе с карточкой: скачивание берёт его
        # отсюда, а не ищет позицию заново по id, потому что id это
        # последний сегмент URL и он совпадает у разных позиций.
        "src": i["photos"][0] if i.get("photos") else "",
        "name": i["name"],
        # Локальная оптимизированная копия, если она уже есть. Пока файла нет,
        # ссылка ведёт на адрес на сайте заказчика: битая картинка в карточке
        # хуже тяжёлой, а второй вариант точно существует.
        "img": photo_src(i),
        "method": "Печать обложки и блока рекламных полей",
        "specs": specs_from_name(i["name"], tiers),
    }
    if siblings and i.get("photos"):
        same_photo = [" ".join(x["name"].split())
                      for x in siblings
                      if x is not i and x.get("photos")
                      and x["photos"][0] == i["photos"][0]]
        if same_photo:
            own = " ".join(i["name"].split())
            others = [n for n in same_photo if n != own]
            if others:
                item["specs"] += ". Варианты: " + ", ".join(others[:4])
                item["variantsOf"] = others
    if i.get("price", {}).get("raw"):
        # Кладём настоящую цену с сайта. render.js вырежет её из catalog.js,
        # потому что showPrices = false. Если заказчик разрешит показывать
        # цены, достаточно поменять флаг, пересборка занимает секунды.
        item["priceFrom"] = i["price"]["raw"]
        item["priceSource"] = i["url"]
    return item


