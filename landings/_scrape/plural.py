# -*- coding: utf-8 -*-
"""Согласование числительных с существительными по-русски.

Зачем. Число и слово в русском языке связаны: 1 позиция, 2 позиции,
5 позиций, но 21 позиция и 31 позиция снова в единственном числе.
Подстановка числа без формы даёт «3 групп товаров» и «31 позиций».
На странице это видно сразу и выглядит как неграмотный исполнитель,
а это ровно то впечатление, которое лендинг должен оставлять противоположным.

Правило. Берутся последние две цифры, потому что исключения живут именно
там: 11, 12, 13, 14, а также 111, 112, 113, 114.
- n % 10 == 1 и n % 100 != 11  → одна, одна позиция
- n % 10 в 2..4 и n % 100 не в 12..14 → две, две позиции
- иначе → много, много позиций

Число 0 берёт форму множественного: «0 позиций» верно.

Использование:
    >>> plural(1, "позиция", "позиции", "позиций")
    'позиция'
    >>> plural(3, "группа", "группы", "групп")
    'группы'
    >>> plural(31, "позиция", "позиции", "позиций")
    'позиция'
"""
from __future__ import annotations

import sys

sys.stdout.reconfigure(encoding="utf-8")


def plural(n: int, one: str, few: str, many: str) -> str:
    """Возвращает слово в форме, согласованной с числом n."""
    n = int(n)
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many


if __name__ == "__main__":
    # Самопроверка на всех числах от 0 до 200 плюс круглые сверху.
    # Смысл проверки не в красоте, а в том, что правило исключений
    # легко переписать неправильно и получить «11 позиция».
    bad = []
    for n in list(range(0, 201)) + [1000, 1001, 1011, 1021, 1101, 1111]:
        want = ("позиция" if n % 10 == 1 and n % 100 != 11
                else "позиции" if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14)
                else "позиций")
        got = plural(n, "позиция", "позиции", "позиций")
        if got != want:
            bad.append((n, got, want))
    for g, w in ((1, "группа"), (2, "группы"), (5, "групп"), (11, "групп"),
                 (21, "группа"), (22, "группы"), (101, "группа"), (111, "групп")):
        got = plural(g, "группа", "группы", "групп")
        if got != w:
            bad.append((g, got, w))
    if bad:
        print("РАСХОЖДЕНИЯ:")
        for b in bad:
            print("  ", b)
        raise SystemExit(1)
    print("проверено 207 чисел: все формы верны")