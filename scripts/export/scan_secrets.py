"""Найти секреты в файлах, которые git отслеживает.

Зачем отдельный гейт, если есть .gitignore. .gitignore защищает от
того, что попадёт в коммит. Он не защищает от того, что уже попало:
если секрет однажды закоммитили, а потом убрали из файла, он навсегда
остаётся в истории, и .gitignore про это ничего не знает. Так и
случилось с client_secret Яндекса: в рабочем файле его нет, в истории
он есть начиная с первого коммита.

Что проверяется. Только отслеживаемые git файлы, потому что
неотслеживаемые ещё не уехали никуда и чинятся добавлением в
.gitignore. Проверяются восемь форм секретов, которые встречаются в
этом проекте или в файлах, которые присылали извне.

Что гейт не умеет. Он не умеет чинить историю. Если секрет уже
закоммичен, гейт скажет об этом и остановит сборку, но убрать его из
истории и отозвать придётся вручную.
"""

import os
import re
import subprocess
import sys

sys.stdout.reconfigure(encoding="utf-8")

ROOT = r"C:\susa ai\2026 cifra audit"

# Формы секретов: имя во втором столбце читается в отчёте.
PATTERNS = [
    # Отдельный токен, а не часть URL. Границы обязательны: первый
    # прогон поймал 32 hex символа в имени файла картинки внутри
    # пути, и без границ гейт врал на каждом разобранном URL.
    (r"(?<![/\w])[0-9a-f]{32}(?![/\w])",
     "идентификатор приложения, отдельно от URL"),
    (r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b",
     "uuid"),
    (r"client_secret\s*[=:]\s*[\"\'][^\"\']{8,}", "client_secret"),
    # Плейсхолдер 12345678 в вызовах целей не всплывает подстановкой
    # конфига: подставляется только инициализация, а цели в шаблоне
    # захардкожены. Проверка идёт по любой цифре, а не по 12345678,
    # иначе новый плейсхолдер пройдёт незамеченным.
    (r"\bym\(\d{4,}\b", "счётчик Метрики, зашитый в код"),
    (r"password\s*[=:]\s*[\"\'][^\"\']{6,}", "пароль в коде"),
    (r"passwd\s*[=:]\s*[\"\'][^\"\']{6,}", "пароль в коде"),
    (r"\bAPI_?KEY\s*[=:]\s*[\"\'][A-Za-z0-9_\-]{16,}", "api-ключ"),
    (r"\btoken\s*[=:]\s*[\"\'][A-Za-z0-9_\-\.]{20,}", "токен в коде"),
]

# Явные исключения: файлы, где наличие строки ожидаемо и разобрано.
ALLOW = {
    "scripts/export/yandex_oauth.py": "хранит LEAKED_CLIENT_ID как маркер "
                                      "утечки и сверяет с ним текущий, "
                                      "значение не используется как секрет",
    "scripts/export/scan_secrets.py": "сам список шаблонов",
    ".gitignore": "пояснения про секреты",
    # Письма в поддержку. Идентификатор приложения в них не случаен,
    # он и есть предмет обращения, и без него поддержка не ответит.
    "scripts/export/APP_RIGHTS.md": "документ для поддержки, идентификатор "
                                     "приложения в нём и есть предмет "
                                     "обращения",
    "scripts/export/SUPPORT_METRIKA.txt": "то же, письмо в поддержку",
}

SKIP_DIRS = (".git", "node_modules", "__pycache__", ".wrangler")


def tracked():
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True,
                         text=True, encoding="utf-8", errors="replace")
    return [l for l in (out.stdout or "").splitlines() if l.strip()]


def main():
    files = tracked()
    print("отслеживаемых файлов: %d" % len(files))
    found = []
    for rel in files:
        if rel in ALLOW:
            continue
        if any(("/" + d + "/") in ("/" + rel) for d in SKIP_DIRS):
            continue
        if not rel.endswith((".py", ".js", ".json", ".md", ".html", ".txt",
                             ".bat", ".yml", ".yaml", ".sh")):
            continue
        p = os.path.join(ROOT, rel)
        if not os.path.isfile(p):
            continue
        try:
            body = open(p, encoding="utf-8").read()
        except (OSError, UnicodeDecodeError):
            continue
        # Документация может цитировать баг, и такая цитата не считается
        # утечкой: инлайн-код в markdown это именно цитата. Совпадение
        # вне кавычек остаётся находкой, поэтому секрет, вставленный в
        # документацию как пример правильного кода, всё равно будет
        # пойман.
        # Перенос строки внутри кавычек разрешён: длинная цифра или
        # длинный вызов в документации переносятся, и при запрете на
        # перенос цитата не распознавалась. Первая версия искала пару
        # кавычек в одной строке и потому пропустила описание бага
        # там, где оно как раз и было.
        code_spans = set()
        for cm in re.finditer(r"`[^`]*`", body):
            for k in range(cm.start(), cm.end()):
                code_spans.add(k)

        for pat, name in PATTERNS:
            for m in re.finditer(pat, body, re.I):
                if rel.endswith(".md") and m.start() in code_spans:
                    continue
                line = body[:m.start()].count("\n") + 1
                snippet = body.splitlines()[line - 1].strip()[:90]
                found.append((rel, line, name, snippet))

    print()
    if found:
        print("НАЙДЕНО В ОТСЛЕЖИВАЕМЫХ ФАЙЛАХ: %d" % len(found))
        for rel, line, name, sn in found:
            print("  %s:%d  %s" % (rel, line, name))
            print("      %s" % sn)
        print()
        print("Что делать: если это рабочее значение, перенести в .env и")
        print("читать оттуда. Если значение уже было в коммите, гейт не")
        print("поможет: его надо отозвать у провайдера и убрать из истории")
        print("git, иначе оно останется в клонах и в origin.")
        return 1
    print("секретов в отслеживаемых файлах не найдено")
    return 0


if __name__ == "__main__":
    sys.exit(main())
