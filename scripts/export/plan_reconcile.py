def sp(n):
    return "{:,}".format(int(n)).replace(",", "\u00a0")


def rows_of(p):
    if not os.path.isfile(p):
        return [], []
    r = [x for x in csv.reader(io.StringIO(
        open(p, encoding="utf-8-sig").read())) if any(y.strip() for y in x)]
    return ([c.strip() for c in r[0]], r[1:]) if r else ([], [])


