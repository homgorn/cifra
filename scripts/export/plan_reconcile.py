_h, _r = rows_of(os.path.join(EX, "traffic_by_source.csv"))
sp_total = 0
sp_search = 0
if _r:
    _si, _vi = _h.index("source"), _h.index("visits")
    for _row in _r:
        if len(_row) > _vi:
            try:
                _v = int(_row[_vi])
            except ValueError:
                continue
            sp_total += _v
            if _row[_si].strip() == "Поиск":
                sp_search = _v
pct_search = 100.0 * sp_search / sp_total if sp_total else 0

_h2, _r2 = rows_of(os.path.join(WM, "all_queries_positions.csv"))
