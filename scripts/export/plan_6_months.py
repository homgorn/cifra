def read_csv_rows(p):
    if not os.path.isfile(p):
        return [], []
    rows = list(csv.reader(io.StringIO(
        open(p, encoding="utf-8-sig").read())))
    rows = [r for r in rows if any(x.strip() for x in r)]
    if not rows:
        return [], []
    return [c.strip() for c in rows[0]], rows[1:]


def cls(q):
    l = q.lower()
    brand = any(b in l for b in BRAND)
    geo = any(c in l for c in CITIES)
    svc = any(s in l for s in SERVICE)
    if brand and svc:
        return "бренд + услуга"
    if brand:
        return "бренд"
    if svc and geo:
        return "услуга + город"
    if geo:
        return "город без услуги"
    if svc:
        return "услуга без города"
    return "прочее"


def sp(n):
    return "{:,}".format(int(n)).replace(",", "\u00a0")


