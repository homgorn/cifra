# Приоритет блокировки: сначала узкие технические, потом бренд, потом опечатки.
BLOCK_ALL = BLOCK_TECH + BLOCK_BRAND + BLOCK_TYPO


def has_print_marker(phrase):
    return bool(PRINT_MARKERS.search(phrase.lower()))


def classify_phrase(phrase):
    """Возвращает (корзина, код, причина)."""
    p = phrase.lower().strip()
    toks = _tokens(p)
    marker = has_print_marker(p)

    # 1. Технический мусор: всегда в BLOCK.
    for code, reason, pattern in BLOCK_ALL:
        if re.search(pattern, p, re.IGNORECASE):
            return "BLOCK", code, reason

    # 2. Мусор распознавания как отдельное слово.
    if toks & GARBAGE_TOKENS:
        return "BLOCK", "D1", ("мусор распознавания или опечатка, "
                               "такого спроса в реальности нет")

    # 3. Маркер услуги есть: фраза наша, уходим в KEEP.
    if marker:
        return "KEEP", "", ""

    # 4. Опечатка в живой фразе: показываем, не выкидываем.
    if toks & TYPO_TOKENS:
        return "REVIEW", "R9", "опечатка внутри запроса, показать человеку"

    # 5. Маркера нет: смотрим, какая это отрасль.
    for code, reason, pattern in BLOCK_OTHER:
        if re.search(pattern, p, re.IGNORECASE):
            return "BLOCK", code, reason

    # 6. Ни отрасли, ни маркера: смежный спрос, решает человек.
    for code, reason, pattern in REVIEW_RULES:
        if re.search(pattern, p, re.IGNORECASE):
            return "REVIEW", code, reason

    # 7. Ничего не сработало: подозрение на мусор, но не уверен.
    if len(p.split()) <= 2:
        return "REVIEW", "R0", "короткая фраза без маркера услуги, нужен взгляд"
    return "REVIEW", "R8", "не распознана как услуга типографии"


def load_queries():
    """Все уникальные фразы из ядра и годового топа, без среза."""
    rows = []
    seen = set()

    if os.path.isfile(WM_DATA):
        t = open(WM_DATA, encoding="utf-8").read()
        d = json.loads(t[t.index("{"):].rstrip().rstrip(";"))
        for r in d.get("queryClusters") or []:
            q = (r.get("q") or "").strip()
            if q and q not in seen:
                seen.add(q)
                rows.append({"phrase": q, "source": "ядро Вебмастера",
                             "group": r.get("c", "Прочие"),
                             "pos": r.get("p", ""), "url": r.get("u", "")})

    if os.path.isdir(WM):
        day = sorted(d for d in os.listdir(WM)
                     if os.path.isdir(os.path.join(WM, d)))[-1]
        f = os.path.join(WM, day, "queries_12m", "q_popular_shows_12m.json")
        if os.path.isfile(f):
            data = json.load(open(f, encoding="utf-8"))
            for q in data.get("queries", []):
                text = (q.get("query_text") or "").strip()
                if text and text not in seen:
                    seen.add(text)
                    rows.append({"phrase": text, "source": "годовой топ по показам",
                                 "group": "", "pos": "", "url": ""})
    return rows


def read_classifier():
    """Достаёт cluster_of из build_wm_data.py, не выполняя весь скрипт."""
    src = open(os.path.join(ROOT, "scripts", "export", "build_wm_data.py"),
               encoding="utf-8").read()
    start = src.find("CLUSTER_RULES = [")
    end = src.find("CLUSTER_PAGE = {")
    if start < 0 or end < 0:
        return lambda q: "Прочие"
    ns = {}
    exec(src[start:end], ns)
    return ns["cluster_of"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stats", action="store_true",
                    help="показать статистику, файлы не перезаписывать")
    args = ap.parse_args()

    rows = load_queries()
    cluster = read_classifier()
    baskets = {"KEEP": [], "REVIEW": [], "BLOCK": []}

    for r in rows:
        verdict, code, reason = classify_phrase(r["phrase"])
        r["verdict"], r["code"], r["reason"] = verdict, code, reason
        if not r["group"]:
            r["group"] = cluster(r["phrase"])
        # Кластер «Прочие» в Topvisor не грузим никогда. Это свалка:
        # в неё попадает всё, что не описано правилом, и аналитика
        # по ней бесполезна. Такие фразы идут человеку на разбор.
        if verdict == "KEEP" and r["group"] == "Прочие":
            verdict = "REVIEW"
            r["verdict"] = verdict
            r["code"] = "R10"
            r["reason"] = "релевантна, но не попала ни в один кластер"
        baskets[verdict].append(r)

    print("Всего уникальных фраз: %d" % len(rows))
    print("  KEEP   импортировать:  %d" % len(baskets["KEEP"]))
    print("  REVIEW показать:       %d" % len(baskets["REVIEW"]))
    print("  BLOCK  не наш спрос:   %d" % len(baskets["BLOCK"]))
    print()

    for name in ("BLOCK", "REVIEW"):
        items = baskets[name]
        if not items:
            continue
        print("%s по причинам:" % name)
        for (code, reason), n in Counter((x["code"], x["reason"])
                                         for x in items).most_common():
            print("  %-4s %-56s %d" % (code, reason, n))
        print()
        print("Примеры %s:" % name)
        for x in items[:10]:
            print("  %-44s [%s] %s" % (x["phrase"][:44], x["code"], x["reason"]))
        print()

    kept_groups = Counter(x["group"] for x in baskets["KEEP"])
    print("KEEP по группам:")
    for g, c in kept_groups.most_common():
        print("  %-24s %d" % (g, c))

    if args.stats:
        return 0

    os.makedirs(EXPORT_DIR, exist_ok=True)
    out_keep = os.path.join(EXPORT_DIR, "import_queries.csv")
    with open(out_keep, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["phrase", "group", "source",
                                           "avg_position", "target_url"])
        w.writeheader()
        for r in baskets["KEEP"]:
            w.writerow({"phrase": r["phrase"], "group": r["group"],
                        "source": r["source"], "avg_position": r["pos"],
                        "target_url": r["url"]})

    for name, fname in (("REVIEW", "review_queries.csv"),
                        ("BLOCK", "blocked_queries.csv")):
        p = os.path.join(EXPORT_DIR, fname)
        with open(p, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["phrase", "code", "reason",
                                               "group", "source"])
            w.writeheader()
            for r in baskets[name]:
                w.writerow({"phrase": r["phrase"], "code": r["code"],
                            "reason": r["reason"], "group": r["group"],
                            "source": r["source"]})

    print()
    print("Записано:")
    for p in (out_keep,
              os.path.join(EXPORT_DIR, "review_queries.csv"),
              os.path.join(EXPORT_DIR, "blocked_queries.csv")):
        print("  %s" % os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
